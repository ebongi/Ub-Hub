// Generates the timetable seed SQL from the university's timetable PDF.
//
// syncfusion_flutter_pdf needs the Flutter engine, so this runs under
// `flutter test` instead of `dart run`. It is skipped unless TIMETABLE_PDF
// is set:
//
//   TIMETABLE_PDF="/path/to/timetable.pdf" \
//   TIMETABLE_SEMESTER="2026/2027 First Semester" \
//   TIMETABLE_OUT="supabase/migrations/20261019120001_seed_timetable.sql" \
//   flutter test tool/generate_timetable_seed_test.dart
//
// The seed replaces the whole table (one semester at a time), in a single
// transaction, so rerunning/reapplying it is safe.
import 'dart:io';

import 'package:flutter_test/flutter_test.dart';
import 'package:go_study/services/timetable_entry.dart';
import 'package:go_study/services/timetable_pdf_reader.dart';

String _q(String? s) => s == null ? 'NULL' : "'${s.replaceAll("'", "''")}'";

void main() {
  final pdf = Platform.environment['TIMETABLE_PDF'];
  final semester =
      Platform.environment['TIMETABLE_SEMESTER'] ?? 'unknown semester';
  final out = Platform.environment['TIMETABLE_OUT'] ??
      'supabase/migrations/seed_timetable.sql';

  test('generate timetable seed SQL', () {
    final result = TimetablePdfReader.parse(File(pdf!).readAsBytesSync());

    if (result.classes.isEmpty) {
      fail('No class rows found — the PDF is not in the supported layout.');
    }
    if (result.skipped.isNotEmpty) {
      // ignore: avoid_print
      print('SKIPPED (not imported):\n${result.skipped.join('\n')}');
    }

    final rows = result.classes.map((c) {
      return '(${_q(c.department)}, ${_q(c.program)}, ${_q(c.listedCode)}, '
          '${c.dayOfWeek}, ${_q(TimetableEntry.formatTime(c.startMinutes))}, '
          '${_q(TimetableEntry.formatTime(c.endMinutes))}, ${_q(c.hall)}, '
          '${_q(c.lecturers)}, ${_q(semester)})';
    }).join(',\n');

    File(out).writeAsStringSync('''
-- Timetable seed: $semester
-- ${result.classes.length} class slots, ${result.programs.length} programs.
-- Generated by tool/generate_timetable_seed_test.dart from the university's
-- teaching timetable PDF; regenerate it each semester. Replaces the entire
-- timetable_classes table (users' chosen course codes are kept).

BEGIN;

DELETE FROM timetable_classes;

INSERT INTO timetable_classes
  (department, program, course_code, day_of_week, start_time, end_time, hall, lecturers, semester)
VALUES
$rows;

COMMIT;
''');
    // ignore: avoid_print
    print('Wrote ${result.classes.length} rows to $out '
        '(${result.skipped.length} skipped)');
  }, skip: pdf == null ? 'set TIMETABLE_PDF to generate the seed' : false);
}
